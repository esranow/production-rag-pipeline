import logging
import requests
from typing import List, Dict, Any, Optional
from src.core.config import settings
from src.generation.prompts import RAG_SYSTEM_PROMPT, build_rag_prompt

logger = logging.getLogger(__name__)


class GroundedLLMClient:
    """
    Resilient Grounded LLM Client for Google Gemini.
    Uses google.genai SDK if available, with direct REST API fallback to bypass
    any environment or namespace import issues.
    """

    def __init__(self, model_name: Optional[str] = None, api_key: Optional[str] = None):
        self.model_name = model_name or settings.DEFAULT_LLM_MODEL
        self.api_key = api_key or settings.GEMINI_API_KEY
        self.sdk_client = None

        try:
            from google import genai
            self.sdk_client = genai.Client(api_key=self.api_key)
            logger.info("GroundedLLMClient using google.genai SDK.")
        except Exception as e:
            logger.info(f"SDK unavailable ({e}); using direct Gemini REST API.")
            self.sdk_client = None

    def _generate_via_rest(self, prompt: str, system_instruction: str) -> str:
        clean_model = self.model_name.replace("models/", "")
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{clean_model}:generateContent?key={self.api_key}"
        payload = {
            "system_instruction": {
                "parts": [{"text": system_instruction}]
            },
            "contents": [
                {
                    "parts": [{"text": prompt}]
                }
            ],
            "generationConfig": {
                "temperature": 0.2
            }
        }
        resp = requests.post(url, json=payload, timeout=45)
        if resp.status_code != 200:
            # If 503 or 404, try fallback model gemini-2.5-flash-lite
            if clean_model != "gemini-2.5-flash-lite":
                fallback_url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-lite:generateContent?key={self.api_key}"
                fallback_resp = requests.post(fallback_url, json=payload, timeout=45)
                if fallback_resp.status_code == 200:
                    candidates = fallback_resp.json().get("candidates", [])
                    if candidates and "content" in candidates[0]:
                        return candidates[0]["content"]["parts"][0]["text"].strip()
            raise RuntimeError(f"Gemini API Error ({resp.status_code}): {resp.text}")

        candidates = resp.json().get("candidates", [])
        if candidates and "content" in candidates[0]:
            return candidates[0]["content"]["parts"][0]["text"].strip()
        return "No response generated by model."

    def generate_answer(
        self,
        query: str,
        retrieved_chunks: List[Dict[str, Any]],
        temperature: float = 0.2
    ) -> Dict[str, Any]:
        """Generates an answer strictly grounded in the retrieved chunks with citations."""
        if not retrieved_chunks:
            return {
                "answer": "I do not have sufficient information in the provided context to answer this question.",
                "model": self.model_name,
                "chunks_cited": []
            }

        user_prompt = build_rag_prompt(query, retrieved_chunks)

        # 1. Try SDK if initialized
        if self.sdk_client:
            try:
                full_prompt = f"{RAG_SYSTEM_PROMPT}\n\n{user_prompt}"
                response = self.sdk_client.models.generate_content(
                    model=self.model_name,
                    contents=full_prompt,
                )
                return {
                    "answer": response.text.strip(),
                    "model": self.model_name,
                    "chunks_cited": retrieved_chunks
                }
            except Exception as e:
                logger.warning(f"SDK generation failed ({e}), attempting REST fallback.")

        # 2. Direct REST fallback
        try:
            answer = self._generate_via_rest(prompt=user_prompt, system_instruction=RAG_SYSTEM_PROMPT)
            return {
                "answer": answer,
                "model": self.model_name,
                "chunks_cited": retrieved_chunks
            }
        except Exception as e:
            return {
                "answer": f"Generation error: {str(e)}",
                "model": self.model_name,
                "chunks_cited": retrieved_chunks
            }
